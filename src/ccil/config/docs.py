def audit_rows(ledger_path: str | Path) -> list[dict]:
    """Classify every ledger parameter and every key the legacy code read; raise if any is unclassified."""
    ledger = json.loads(Path(ledger_path).read_text())
    by_legacy = {legacy: p.key for p in REGISTRY.values() for legacy in p.legacy}
    keys = [(x["key"], x["class"]) for x in ledger["parameters"]] + \
           [(k, "-") for k in LITERALS if not k.startswith("literal:")]
    rows, missing = [], []
    for key, cls in keys:
        top = key.split(".")[0]
        if key in by_legacy:
            target, status, note = by_legacy[key], REGISTRY[by_legacy[key]].status, REGISTRY[by_legacy[key]].milestone
        elif key in LITERALS:
            target, note = LITERALS[key]
            status = REGISTRY[target].status if target in REGISTRY else target
            target = target if target in REGISTRY else "-"
        elif key in DROPPED:
            target, status, note = "-", "dropped", DROPPED[key]
        elif key in UNSUPPORTED or top in UNSUPPORTED:
            target, status, note = "-", "deferred", UNSUPPORTED.get(key) or UNSUPPORTED[top]
        else:
            missing.append(key)
            continue
        rows.append({"legacy": key, "ledger_class": cls, "canonical": target, "status": status, "note": note})
    if missing:
        raise ValueError(f"unclassified parameters: {missing}")
    return rows


def render_audit(ledger_path: str | Path) -> str:
    rows = audit_rows(ledger_path)
    counts = {}
    for r in rows:
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    lines = ["# Parameter audit (generated)", "",
             "<!-- Generated by `python -m ccil config audit`; edit src/ccil/config/, not this file. -->", "",
             "Every behavior-affecting value recorded in the reproducibility ledger, and every key the legacy "
             "code read, with its canonical key and status. Generation fails if any value is unclassified.", "",
             "Status counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + ".", "",
             "| Legacy value | Ledger class | Canonical key | Status | Note |", "|---|---|---|---|---|"]
    lines += [f"| `{r['legacy']}` | {r['ledger_class']} | {('`' + r['canonical'] + '`') if r['canonical'] != '-' else '-'} | "
              f"{r['status']} | {r['note']} |" for r in rows]
    return "\n".join(lines) + "\n"
