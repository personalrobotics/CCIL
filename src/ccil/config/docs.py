def _domain(p) -> str:
    if p.choices:
        return ", ".join(f"`{c}`" for c in p.choices)
    if p.low is None and p.high is None:
        return "-"
    lo = "-inf" if p.low is None else p.low
    hi = "inf" if p.high is None else p.high
    return f"{'(' if p.low_open else '['}{lo}, {hi}{')' if p.high_open else ']'}"


def render_parameters() -> str:
    lines = ["# Configuration parameters (generated)", "",
             "<!-- Generated by `python -m ccil config docs`; edit src/ccil/config/params.py, not this file. -->", "",
             (resolve_mod.__doc__ or "").strip().replace("\n", " "), "",
             "Values in files are YAML; numbers with units may be written `\"<n> <unit>\"` with exactly the declared "
             "unit. Command-line values are parsed by type: booleans accept only `true` or `false`; lists accept "
             "`a,b` or `[a, b]`; nullable values accept `null`.", "",
             "`declared` parameters are validated and documented now and consumed by the milestone shown.", ""]
    for stage in STAGES:
        params = [p for p in REGISTRY.values() if p.stage == stage]
        if not params:
            continue
        lines += [f"## {stage}", "", "| Key | Type | Default | Units | Domain | Status | Description | Rationale | Replaces |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for p in params:
            status = p.status + (f" ({p.milestone})" if p.milestone else "")
            replaces = ", ".join(f"`{k}`" for k in p.legacy) or "-"
            lines.append(f"| `{p.key}` | {p.type} | `{json.dumps(p.default)}` | {p.units} | {_domain(p)} | {status} | "
                         f"{p.description} | {p.rationale} | {replaces} |")
        lines.append("")
    lines += ["## Cross-field rules", ""] + [f"- `{name}`: {', '.join(f'`{k}`' for k in keys)}" for name, keys, _ in RULES]
    return "\n".join(lines) + "\n"


