"""Generate the normative schema reference from the specs, its one canonical source."""
from __future__ import annotations

from . import io, labels, trajectories


def _table(specs) -> list[str]:
    rows = ["| Field | Kind | Shape | Units | Required | Description |", "|---|---|---|---|---|---|"]
    for s in specs:
        shape = "(" + ", ".join(map(str, s.shape)) + ("," if len(s.shape) == 1 else "") + ")"
        rows.append(f"| `{s.name}` | {s.kind} | {shape} | {s.units} | {'yes' if s.required else 'no'} | {s.description} |")
    return rows


def _names(keys) -> str:
    return ", ".join(f"`{k}`" for k in sorted(keys)) or "none"


def _fields(fields) -> list[str]:
    return ["| Field | Type | Description |", "|---|---|---|"] + [f"| `{n}` | `{t}` | {d} |".replace(" | None", " \\| None") for n, t, d in fields]


def render() -> str:
    t, c = trajectories, labels
    lines = [
        "# Data schemas (generated)",
        "",
        "<!-- Generated by `uv run ccil schema docs`; edit the specs in src/ccil/schema/, not this file. -->",
        "",
        f"## `{t.SCHEMA}` {t.VERSION[0]}.{t.VERSION[1]}",
        "",
        (t.__doc__ or "").strip().split("\n\n", 1)[1].replace("\n", " "),
        "",
        "### Episode", "", *_fields(t.EPISODE_FIELDS), "",
        "### Arrays", "", *_table(t.ARRAY_SPECS), "",
        f"Modality names match `{t.MODALITY.pattern}`.", "",
        "### File layout (.npz)", "",
        f"Required: {', '.join(f'`{k}`' for k in sorted(io.TRAJ_REQUIRED))}, and `obs/<modality>` per modality. "
        f"Optional: {_names(io.TRAJ_OPTIONAL)}. Per-frame arrays are concatenated "
        "across episodes in `episode_ids` order and split by `episode_lengths`.", "",
        f"## `{c.SCHEMA}` {c.VERSION[0]}.{c.VERSION[1]}",
        "",
        (c.__doc__ or "").strip().split("\n\n", 1)[1].replace("\n", " "),
        "",
        "### Fields", "", *_fields(c.FIELDS), "",
        "### Arrays", "", *_table(c.ARRAY_SPECS), "",
        f"Candidate modality names match `{c.CANDIDATE_MODALITY.pattern}`.", "",
        f"Built-in reason codes: {', '.join(f'`{r}`' for r in c.REASON_CODES)}. Extension codes match "
        f"`{c.EXTENSION_REASON.pattern}`; reserved namespaces: {', '.join(f'`{n}`' for n in c.RESERVED_NAMESPACES)}.", "",
        "### File layout (.npz)", "",
        f"Required: {', '.join(f'`{k}`' for k in sorted(io.CAND_REQUIRED))}, plus `obs/<modality>`, "
        f"`target/<modality>`, and `meas/<name>`. Optional: {_names(io.CAND_OPTIONAL)}. "
        f"`meta` holds {_names(io.CAND_META)}.", "",
        "## Compatibility", "",
        (io.__doc__ or "").strip().split("\n\n", 1)[1].replace("\n", " "), "",
    ]
    return "\n".join(lines)
